def run():
    db = SessionLocal()
    try:
        orinbosar = db.query(models.Employee).filter(
            models.Employee.full_name == ORINBOSAR_FULLNAME
        ).first()
        if not orinbosar:
            print(f"[XATO] '{ORINBOSAR_FULLNAME}' xodimi topilmadi, to'xtatildi.")
            return

        creator = db.query(models.Employee).filter(
            models.Employee.role == models.RoleEnum.superadmin
        ).first()

        dept_cache: dict[str, int] = {}
        created, skipped = 0, 0

        for row in IJRO_DATA:
            exists = db.query(models.IjroDocument).filter(
                models.IjroDocument.hujjat_raqami == row["hujjat_raqami"],
                models.IjroDocument.sarlavha == row["sarlavha"],
            ).first()
            if exists:
                skipped += 1
                continue

            ijro_muddati = None
            if row.get("ijro_muddati"):
                ijro_muddati = datetime.strptime(row["ijro_muddati"], "%Y-%m-%d")
            hujjat_sanasi = row.get("hujjat_sanasi")

            doc = models.IjroDocument(
                tur=models.IjroDocTur.kiruvchi,
                manba=MANBA,
                hujjat_raqami=row["hujjat_raqami"],
                hujjat_sanasi=hujjat_sanasi,
                sarlavha=row["sarlavha"],
                mazmun=row["mazmun"],
                qoshimcha_malumot=row.get("qoshimcha_malumot") or None,
                masul_orinbosar_id=orinbosar.id,
                davriyligi=DAVRIYLIGI,
                kelishuvchi_tashkilotlar=KELISHUVCHI,
                ijro_muddati=ijro_muddati,
                created_by=creator.id if creator else None,
            )
            db.add(doc)
            db.flush()

            bolim_ids = []
            for b in row["bolimlar"]:
                dept_name = b["dept_name"]
                if dept_name not in dept_cache:
                    dept = db.query(models.Department).filter(
                        models.Department.name == dept_name
                    ).first()
                    if not dept:
                        print(f"[OGOHLANTIRISH] bo'lim topilmadi: {dept_name}")
                        continue
                    dept_cache[dept_name] = dept.id
                dept_id = dept_cache[dept_name]
                bolim_ids.append(dept_id)

                ab = models.IjroDocBolim(doc_id=doc.id, bolim_id=dept_id)

                xodim_full_name = b.get("xodim_full_name")
                if xodim_full_name:
                    xodim = db.query(models.Employee).filter(
                        models.Employee.full_name == xodim_full_name,
                        models.Employee.department_id == dept_id,
                    ).first()
                    if xodim:
                        ab.xodim_id = xodim.id
                        ab.xodim_assigned_at = datetime.utcnow()

                db.add(ab)
                db.flush()

                if ab.xodim_id:
                    db.add(models.IjroDocBolimAssignLog(
                        doc_bolim_id=ab.id,
                        xodim_id=ab.xodim_id,
                        assigned_by=creator.id if creator else ab.xodim_id,
                    ))

            db.commit()
            created += 1
            print(f"[OK] {row['hujjat_raqami']} — {row['sarlavha'][:40]} (bo'limlar: {len(bolim_ids)})")

        print(f"Yakun: {created} ta yangi hujjat yaratildi, {skipped} ta oldin mavjud bo'lgani uchun o'tkazib yuborildi.")
    finally:
        db.close()


if __name__ == "__main__":
    run()
